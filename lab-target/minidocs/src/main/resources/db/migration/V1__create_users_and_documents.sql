-- Tabella degli utenti
CREATE TABLE lab_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE
);

-- Tabella dei documenti
CREATE TABLE lab_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(100) NOT NULL,
    content TEXT NOT NULL,
    owner_id BIGINT NOT NULL,

    CONSTRAINT fk_lab_documents_owner
    FOREIGN KEY (owner_id)
    REFERENCES lab_users(id)
);

-- Indice per le ricerche dei documenti tramite proprietario
CREATE INDEX idx_lab_documents_owner_id
    ON lab_documents(owner_id);